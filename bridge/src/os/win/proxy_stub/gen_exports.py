#!/usr/bin/env python3
"""Generate the export list of the stub proxy DLL from a real version.dll.

The list is read from the export table of the DLL the stub stands in for (the
Wine/Proton builtin, or a Windows System32 copy), never typed by hand, so a
missing export is a difference between two binaries and not a typo.

    python3 -I gen_exports.py <path/to/version.dll> > version_exports.h

Stdlib only. Named exports only. A forwarder entry in the source DLL is still
emitted: the stub resolves it at run time with GetProcAddress, which follows
forwarders.
"""
import struct
import sys


def exports(path):
    data = open(path, "rb").read()
    if data[:2] != b"MZ":
        raise SystemExit(f"{path}: no MZ header")
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    if data[pe:pe + 4] != b"PE\0\0":
        raise SystemExit(f"{path}: no PE signature")
    nsect = struct.unpack_from("<H", data, pe + 6)[0]
    opt_size = struct.unpack_from("<H", data, pe + 20)[0]
    opt = pe + 24
    magic = struct.unpack_from("<H", data, opt)[0]
    if magic != 0x20B:
        raise SystemExit(f"{path}: not PE32+ (magic {magic:#x}); use the x86_64 DLL")
    exp_rva, exp_size = struct.unpack_from("<II", data, opt + 112)
    if exp_rva == 0:
        raise SystemExit(f"{path}: no export directory")
    sects = []
    for i in range(nsect):
        s = opt + opt_size + 40 * i
        vsize, va, rsize, rptr = struct.unpack_from("<IIII", data, s + 8)
        sects.append((va, max(vsize, rsize), rptr))

    def off(rva):
        for va, size, rptr in sects:
            if va <= rva < va + size:
                return rva - va + rptr
        raise SystemExit(f"{path}: rva {rva:#x} outside every section")

    def cstr(rva):
        o = off(rva)
        return data[o:data.index(b"\0", o)].decode("ascii")

    e = off(exp_rva)
    (_, _, _, _, name_rva, base, n_funcs, n_names, funcs_rva, names_rva,
     ords_rva) = struct.unpack_from("<IIHHIIIIIII", data, e)
    out = []
    for i in range(n_names):
        nrva = struct.unpack_from("<I", data, off(names_rva) + 4 * i)[0]
        idx = struct.unpack_from("<H", data, off(ords_rva) + 2 * i)[0]
        frva = struct.unpack_from("<I", data, off(funcs_rva) + 4 * idx)[0]
        fwd = cstr(frva) if exp_rva <= frva < exp_rva + exp_size else None
        out.append((cstr(nrva), base + idx, fwd))
    return cstr(name_rva), n_funcs, out


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    dll, n_funcs, names = exports(sys.argv[1])
    print(f"/* GENERATED by gen_exports.py from {dll} ({len(names)} named of "
          f"{n_funcs} exports). Do not edit; regenerate. */")
    print("/* X(name, ordinal_in_source_dll) */")
    for name, ordinal, fwd in sorted(names):
        note = f"  /* forwarder -> {fwd} */" if fwd else ""
        print(f"X({name}, {ordinal}){note}")


if __name__ == "__main__":
    main()
