#!/usr/bin/env python3
"""Generate the export list of the proxy version.dll from a real version.dll.

The list is read from the export table of the DLL the proxy stands in for (the
Wine/Proton builtin, or a Windows System32 copy), never typed by hand, so a
missing export is a difference between two binaries and not a typo. Readers:
ck3_bridge_win (bridge/CMakeLists.txt generates proxy.def from it; proxy.cpp
has one forward per name) and the P3 stub (../win/proxy_stub/).

    python3 -I gen_exports.py <path/to/version.dll> > version_exports.h
    python3 -I gen_exports.py --check <built.dll> <list.h>...

--check compares the named exports of a BUILT proxy with the union of the
X(name, ...) lines of the list files, and exits 1 on any difference (either
direction), printing it; any parse trouble also exits non-zero, never 0.

Stdlib only. Named exports only. A forwarder entry in the source DLL is still
emitted: the stub resolves it at run time with GetProcAddress, which follows
forwarders.
"""
import struct
import sys


def exports(path):
    data = open(path, "rb").read()
    if data[:2] != b"MZ":
        raise SystemExit(f"{path}: no MZ header")
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    if data[pe:pe + 4] != b"PE\0\0":
        raise SystemExit(f"{path}: no PE signature")
    nsect = struct.unpack_from("<H", data, pe + 6)[0]
    opt_size = struct.unpack_from("<H", data, pe + 20)[0]
    opt = pe + 24
    magic = struct.unpack_from("<H", data, opt)[0]
    if magic != 0x20B:
        raise SystemExit(f"{path}: not PE32+ (magic {magic:#x}); use the x86_64 DLL")
    exp_rva, exp_size = struct.unpack_from("<II", data, opt + 112)
    if exp_rva == 0:
        raise SystemExit(f"{path}: no export directory")
    sects = []
    for i in range(nsect):
        s = opt + opt_size + 40 * i
        vsize, va, rsize, rptr = struct.unpack_from("<IIII", data, s + 8)
        sects.append((va, max(vsize, rsize), rptr))

    def off(rva):
        for va, size, rptr in sects:
            if va <= rva < va + size:
                return rva - va + rptr
        raise SystemExit(f"{path}: rva {rva:#x} outside every section")

    def cstr(rva):
        o = off(rva)
        return data[o:data.index(b"\0", o)].decode("ascii")

    e = off(exp_rva)
    (_, _, _, _, name_rva, base, n_funcs, n_names, funcs_rva, names_rva,
     ords_rva) = struct.unpack_from("<IIHHIIIIIII", data, e)
    out = []
    for i in range(n_names):
        nrva = struct.unpack_from("<I", data, off(names_rva) + 4 * i)[0]
        idx = struct.unpack_from("<H", data, off(ords_rva) + 2 * i)[0]
        frva = struct.unpack_from("<I", data, off(funcs_rva) + 4 * idx)[0]
        fwd = cstr(frva) if exp_rva <= frva < exp_rva + exp_size else None
        out.append((cstr(nrva), base + idx, fwd))
    return cstr(name_rva), n_funcs, out


def check(dll_path, lists):
    import re
    want = set()
    for p in lists:
        for line in open(p, encoding="ascii"):
            m = re.match(r"X\(([A-Za-z0-9_]+), *[0-9]+\)", line)
            if m:
                want.add(m.group(1))
    if not want:
        raise SystemExit(f"--check: no X(name, ord) lines in {lists}")
    _, n_funcs, names = exports(dll_path)
    got = {n for n, _, _ in names}
    extra, missing = sorted(got - want), sorted(want - got)
    print(f"{dll_path}: {len(got)} named exports ({n_funcs} total); list: {len(want)}")
    for n in missing:
        print(f"MISSING from the DLL: {n}")
    for n in extra:
        print(f"EXTRA in the DLL (not in the list): {n}")
    if extra or missing or n_funcs != len(got):
        if n_funcs != len(got):
            print(f"the DLL has {n_funcs - len(got)} export(s) without a name")
        raise SystemExit(1)
    print("export table == list")


def main():
    if len(sys.argv) >= 4 and sys.argv[1] == "--check":
        check(sys.argv[2], sys.argv[3:])
        return
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    dll, n_funcs, names = exports(sys.argv[1])
    print(f"/* GENERATED by gen_exports.py from {dll} ({len(names)} named of "
          f"{n_funcs} exports). Do not edit; regenerate. */")
    print("/* X(name, ordinal_in_source_dll) */")
    for name, ordinal, fwd in sorted(names):
        note = f"  /* forwarder -> {fwd} */" if fwd else ""
        print(f"X({name}, {ordinal}){note}")


if __name__ == "__main__":
    main()
