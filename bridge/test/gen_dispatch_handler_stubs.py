#!/usr/bin/env python3
"""Generate WEAK no-op definitions for every action handler declared in
action_dispatch_internal.h  (ck-sozz).

Why this exists
---------------
test_release_handler.cpp drives the REAL do_release_character /
do_set_controlled_character out of the real dispatch_router.cpp — that is the
whole point of the bead: the bug was in the HANDLER's ordering, not in
SessionRegistry, and a test that links only the registry cannot see it.

But dispatch_router.cpp also carries the master dispatch table, which names
~150 handlers that live in other translation units (and, transitively, in the
game). Linking those TUs on the host is impossible.

So: every declared handler gets a WEAK stub here. The three handlers
dispatch_router.cpp defines itself provide STRONG definitions, and a strong
definition always wins over a weak one at link time — so the test runs the real
code and the dispatch table's other entries resolve to inert stubs that the
test never calls.

Generated at build time from the header, so a handler added tomorrow does not
break this test.
"""
import re
import sys


def main(header_path: str, out_path: str) -> int:
    src = open(header_path, encoding="utf-8").read()

    # Join declarations that wrap onto continuation lines, then pick out every
    # `bool do_xxx(...);` at top level of the header.
    flat = re.sub(r",\s*\n\s*", ", ", src)
    decls = re.findall(r"^bool (do_\w+)\(([^;]*?)\);", flat, re.MULTILINE)

    out = []
    out.append("// GENERATED by test/gen_dispatch_handler_stubs.py — do not edit.\n")
    out.append("// Weak no-op definitions for the dispatch table's handlers (ck-sozz).\n")
    out.append("// A strong definition in a linked TU (dispatch_router.cpp) overrides\n")
    out.append("// the matching stub, which is how the test drives the real handler.\n\n")
    out.append("#include <string>\n\n")
    out.append("namespace bridge {\n\n")
    for name, params in decls:
        # Default arguments may not be repeated on the definition.
        params = re.sub(r"\s*=\s*[^,)]+", "", params)
        # Drop parameter names so nothing is unused.
        stripped = []
        for p in params.split(","):
            p = p.strip()
            if not p:
                continue
            stripped.append(re.sub(r"\s*\b\w+$", "", p) if re.search(r"[\w>*&]\s+\w+$", p) else p)
        out.append("__attribute__((weak)) bool %s(%s) { return false; }\n"
                   % (name, ", ".join(stripped)))
    out.append("\n}  // namespace bridge\n")

    text = "".join(out)
    try:
        if open(out_path, encoding="utf-8").read() == text:
            return 0          # unchanged — don't churn the build
    except OSError:
        pass
    open(out_path, "w", encoding="utf-8").write(text)
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.stderr.write("usage: gen_dispatch_handler_stubs.py <header> <out.cpp>\n")
        sys.exit(2)
    sys.exit(main(sys.argv[1], sys.argv[2]))
