"""The linux tarball carries the docs README.txt points at.

smoke16 and smoke17 (2026.11.0, 2026.12.0): docs/reference/tools.md shipped in
the sdist only; the tarball had no docs/ and README.txt pointed at a URL. This
runs release.yml's own "Assemble tarball" script (not a copy of it) in a scratch
tree with stand-ins for the build outputs, and reads the tarball it makes.
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
import tarfile
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
WORKFLOW = ROOT / ".github/workflows/release.yml"
VER = "v0.0.0-test"


def assemble_script() -> str:
    """The `run: |` block of the step named "Assemble tarball", dedented."""
    lines = WORKFLOW.read_text(encoding="utf-8").splitlines()
    i = next(n for n, l in enumerate(lines) if l.strip() == "- name: Assemble tarball")
    assert lines[i + 1].strip() == "run: |", lines[i + 1]
    body, indent = [], None
    for l in lines[i + 2:]:
        if l.strip() and indent is None:
            indent = len(l) - len(l.lstrip())
        if l.strip() and len(l) - len(l.lstrip()) < indent:
            break
        body.append(l[indent:] if l.strip() else "")
    return "\n".join(body) + "\n"


def scratch(tmp: Path) -> Path:
    t = tmp / "tree"
    shutil.copytree(ROOT / "docs", t / "docs")
    (t / "installer").mkdir(parents=True)
    for f in ("install.sh", "uninstall.sh", "README.txt"):
        shutil.copy(ROOT / "installer" / f, t / "installer" / f)
    (t / "installer/bundle_wheels.sh").write_text("#!/bin/sh\nexit 0\n")
    (t / "installer/bundle_wheels.sh").chmod(0o755)
    for f in ("LICENSE", "NOTICE", "THIRD_PARTY_LICENSES.md", "VERSION", "UPSTREAM", "CITATION.cff"):
        (t / f).write_text(f"{f}\n")
    (t / "bridge/build").mkdir(parents=True)
    (t / "bridge/build/libck3_bridge.so").write_bytes(b"\x7fELF")
    (t / "bridge/build/libck3_bridge.so.debug").write_bytes(b"\x7fELF")
    (t / "dist").mkdir()
    (t / "dist/ck3agent-0.0.0-py3-none-any.whl").write_bytes(b"PK")
    (t / "dist/ck3agent-0.0.0.tar.gz").write_bytes(b"\x1f\x8b")
    (tmp / "runner").mkdir()
    (tmp / "runner/notes.md").write_text("notes\n")
    return t


def run_assemble(tmp: Path, tree: Path) -> subprocess.CompletedProcess:
    script = tmp / "assemble.sh"
    script.write_text(assemble_script())
    env = dict(os.environ, VER=VER, RUNNER_TEMP=str(tmp / "runner"), SOURCE_DATE_EPOCH="1700000000")
    # GitHub's `run:` shell for bash steps
    return subprocess.run(["bash", "--noprofile", "--norc", "-eo", "pipefail", str(script)],
                          cwd=tree, env=env, capture_output=True, text=True)


@pytest.mark.skipif(not shutil.which("tar") or not shutil.which("gzip") or not shutil.which("sha256sum"),
                    reason="needs tar, gzip and sha256sum")
def test_the_tarball_ships_the_docs_readme_txt_names(tmp_path):
    if not (ROOT / "docs/reference/tools.md").is_file():
        pytest.skip("docs/reference/tools.md is generated by release/export.py")
    tree = scratch(tmp_path)
    r = run_assemble(tmp_path, tree)
    assert r.returncode == 0, r.stdout + r.stderr
    name = f"ck3agent-{VER}-linux-x86_64"
    with tarfile.open(tree / f"out/{name}.tar.gz") as tf:
        listed = set(tf.getnames())
    for f in ("docs/getting-started.md", "docs/reference/tools.md", "docs/reference/files-and-paths.md",
              "README.txt", "install.sh", "lib/libck3_bridge.so"):
        assert f"{name}/{f}" in listed, f
    named = re.findall(r"\bdocs/[\w/.-]+\.md\b", (ROOT / "installer/README.txt").read_text())
    assert named, "README.txt names no docs file"
    for f in named:
        assert f"{name}/{f}" in listed, f"README.txt names {f}; the tarball lacks it"
    docs = sum(m.size for m in tarfile.open(tree / f"out/{name}.tar.gz").getmembers()
               if m.name.startswith(f"{name}/docs/") and m.isfile())
    print(f"docs/ in the tarball: {docs} bytes uncompressed")


@pytest.mark.skipif(not shutil.which("tar"), reason="needs tar")
def test_the_listing_check_reds_a_tarball_without_tools_md(tmp_path):
    """The workflow's own listing check runs: drop the generated reference and the step fails."""
    tree = scratch(tmp_path)
    (tree / "docs/reference/tools.md").unlink(missing_ok=True)
    r = run_assemble(tmp_path, tree)
    assert r.returncode != 0 and "tarball lacks docs/reference/tools.md" in r.stdout + r.stderr


@pytest.mark.skipif(not shutil.which("tar"), reason="needs tar")
def test_the_listing_check_reds_a_tarball_without_version(tmp_path):
    """README.txt names VERSION (`ck3agent version` prints it); the listing check
    covers it (witness r1 item 10: the check omitted it)."""
    assert re.search(r"^VERSION\b", (ROOT / "installer/README.txt").read_text(), re.M)
    tree = scratch(tmp_path)
    script = assemble_script().replace(
        'cp LICENSE NOTICE THIRD_PARTY_LICENSES.md VERSION UPSTREAM CITATION.cff "$d/"',
        'cp LICENSE NOTICE THIRD_PARTY_LICENSES.md UPSTREAM CITATION.cff "$d/"')
    assert "VERSION UPSTREAM" not in script, "the cp line moved; this row no longer drops VERSION"
    (tmp_path / "assemble.sh").write_text(script)
    env = dict(os.environ, VER=VER, RUNNER_TEMP=str(tmp_path / "runner"), SOURCE_DATE_EPOCH="1700000000")
    r = subprocess.run(["bash", "--noprofile", "--norc", "-eo", "pipefail", str(tmp_path / "assemble.sh")],
                       cwd=tree, env=env, capture_output=True, text=True)
    assert r.returncode != 0 and "tarball lacks VERSION" in r.stdout + r.stderr, r.stdout + r.stderr
