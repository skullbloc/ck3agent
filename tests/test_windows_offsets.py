"""The generated Windows offset headers (re/offsets/windows/) against the identity
the bridge gates on (bridge/src/os/windows/pinned_identity.h). release/export.py
writes both headers from research inputs that do not ship; each names the pinned
ck3.exe it was generated for. A header for another build than the gate's is the one
failure no build step would catch: it compiles, and every offset is wrong."""
from __future__ import annotations

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
PIN = ROOT / "bridge/src/os/windows/pinned_identity.h"
HEADERS = [ROOT / "re/offsets/windows/ck3_offsets.generated.h", ROOT / "re/offsets/windows/ck3_offsets_win.h"]
if not (ROOT / "bridge").is_dir():
    pytest.skip("bridge/ is not part of this tree (sdist)", allow_module_level=True)


def _literal(text: str, name: str) -> str:
    m = re.search(rf"\b{name}\s*=\s*((?:\"[^\"]*\"\s*)+);", text)
    assert m, f"{PIN.name}: {name} not found"
    return "".join(re.findall(r"\"([^\"]*)\"", m.group(1)))


def _pin() -> dict[str, str]:
    text = PIN.read_text(encoding="utf-8")
    size = re.search(r"\bkSizeOfImage\s*=\s*(\d+)\s*;", text)
    base = re.search(r"\bkImageBase\s*=\s*(0x[0-9A-Fa-f]+)ull\s*;", text)
    assert size and base
    return {"codeview": _literal(text, "kCodeViewHex"), "size_of_image": size.group(1),
            "sha256": _literal(text, "kImageSha256"), "label": _literal(text, "kLabel"),
            "image_base": base.group(1).lower()}


@pytest.mark.parametrize("header", HEADERS, ids=lambda p: p.name)
def test_generated_header_names_the_pinned_build(header):
    assert header.is_file(), f"{header.relative_to(ROOT)} is missing: the export generates it"
    text = header.read_text(encoding="utf-8")
    pin = _pin()
    assert text.startswith("// GENERATED by release/export.py (windows_offsets)")
    m = re.search(r"^//   codeview=(\S+) size_of_image=(\d+) sha256=(\S+)$", text, re.M)
    assert m, "no pinned-build line"
    assert (m.group(1), m.group(2), m.group(3)) == (pin["codeview"], pin["size_of_image"], pin["sha256"])
    assert f"): {pin['label']}" in text
    # the inputs it was made from, by sha: each a 64-digit sha256 and a distinct path
    inputs = re.findall(r"^//   ([0-9a-f]{64})  (\S+)$", text, re.M)
    assert len(inputs) >= 7 and len({p for _, p in inputs}) == len(inputs)


def test_the_two_headers_come_from_one_generation():
    heads = []
    for h in HEADERS:
        text = h.read_text(encoding="utf-8")
        heads.append(re.findall(r"^//   (?:[0-9a-f]{64}  \S+|codeview=.*)$", text, re.M))
    assert heads[0] == heads[1]


def test_the_windows_image_base_is_the_pinned_one():
    text = HEADERS[1].read_text(encoding="utf-8")
    m = re.search(r"\bIMAGE_BASE\s*=\s*(0x[0-9A-Fa-f]+)ull\s*;", text)
    assert m and m.group(1).lower() == _pin()["image_base"]
